const connectionString = process.env.DATABASE_URL;

const pool = connectionString ? new Pool({

  connectionString,

  ssl: connectionString.includes('localhost') || connectionString.includes('127.0.0.1')

    ? undefined : { rejectUnauthorized: false },

  max: 5,

  idleTimeoutMillis: 30000,

  connectionTimeoutMillis: 10000,

}) : null;

const db = async (sql, params = []) => {

  if (!pool) throw Object.assign(new Error('DATABASE_URL is not configured'), { statusCode: 500 });

  return pool.query(sql, params);

};

const err = (message, statusCode = 400) => Object.assign(new Error(message), { statusCode });

const makeId = () => randomUUID();

const safeBody = (req) => req.body && typeof req.body === 'object' ? req.body : {};

const normalizeUrl = (raw) => {

  const input = String(raw ?? '').trim();

  if (!input) throw err('URL is required');

  let parsed;

  try { parsed = new URL(/^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(input) ? input : `https\://${input}`); }

  catch { throw err('Invalid URL'); }

  if (!['http:', 'https:'].includes(parsed.protocol)) throw err('Only http and https URLs are allowed');

  return parsed.toString();

};

const statusFor = (link) => {

  if (link.status === 'paused') return 'paused';

  if (link.expiresAt && Number.isFinite(Date.parse(link.expiresAt)) && Date.now() > Date.parse(link.expiresAt)) return 'expired';

  if (Number.isFinite(link.maxClicks) && link.maxClicks > 0 && link.clicks >= link.maxClicks) return 'limit_reached';

  return 'active';

};

const baseUrl = (req) => `${String(req.headers['x-forwarded-proto'] || (req.protocol === 'https' ? 'https' : 'http')).split(',')[0]}://${String(req.headers['x-forwarded-host'] || req.headers.host || 'localhost').split(',')[0]}`;

const presentLink = (req, link) => ({ ...link, status: statusFor(link), shortUrl: `${baseUrl(req)}/r/${link.code}` });

const slug = () => Array.from({ length: 6 }, () => 'abcdefghijkmnpqrstuvwxyz23456789'[Math.floor(Math.random() * 28)]).join('');

const fromLinkRow = (r) => ({

  id: r.id, code: r.code, url: r.url, title: r.title, clicks: Number(r.clicks || 0),

  createdAt: new Date(r.created_at).toISOString(),

  lastVisitedAt: r.last_visited_at ? new Date(r.last_visited_at).toISOString() : null,

  expiresAt: r.expires_at ? new Date(r.expires_at).toISOString() : null,

  maxClicks: r.max_clicks == null ? null : Number(r.max_clicks), status: r.status || 'active',

  folderId: r.folder_id, tags: r.tags || [], campaignId: r.campaign_id, password: r.password,

  utmParams: r.utm_params || undefined, abTest: r.ab_test || undefined, notes: r.notes || '',

});

const fromClickRow = (r) => ({

  id: r.id, linkId: r.link_id, code: r.code, createdAt: new Date(r.created_at).toISOString(),

  referrer: r.referrer || 'direct', referrerDomain: r.referrer_domain || 'direct',

  userAgent: r.user_agent || '', deviceType: r.device_type || 'desktop', browser: r.browser || 'Other',

  os: r.os || 'Other', country: r.country || 'Unknown', countryCode: r.country_code || 'UN',

  city: r.city || '', ip: r.ip || '', variantId: r.variant_id || undefined,

});

const getLink = async (code) => {

  const r = await db('SELECT * FROM links WHERE LOWER(code)=LOWER($1) LIMIT 1', [String(code)]);

  return r.rows[0] ? fromLinkRow(r.rows[0]) : null;

};

const getClicks = async (linkId) => {

  const r = await db('SELECT * FROM clicks WHERE link_id=$1 ORDER BY created_at DESC', [linkId]);

  return r.rows.map(fromClickRow);

};

const json = (value) => value == null ? null : JSON.stringify(value);

// Create or upgrade tables at startup. Safe to run on every local start / serverless cold start.

let schemaPromise;

async function ensureSchema() {

  if (!pool) throw err('DATABASE_URL is not configured', 500);

  if (schemaPromise) return schemaPromise;

  schemaPromise = (async () => {

    await db(`CREATE TABLE IF NOT EXISTS links (

      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL, url TEXT NOT NULL, title TEXT NOT NULL,

      clicks INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

      last_visited_at TIMESTAMPTZ, expires_at TIMESTAMPTZ, max_clicks INTEGER,

      status TEXT NOT NULL DEFAULT 'active', folder_id UUID, tags JSONB NOT NULL DEFAULT '[]'::jsonb,

      campaign_id UUID, password TEXT, utm_params JSONB, ab_test JSONB, notes TEXT NOT NULL DEFAULT ''

    )`);

    await db('CREATE UNIQUE INDEX IF NOT EXISTS links_code_lower_unique ON links (LOWER(code))');

    await db('CREATE INDEX IF NOT EXISTS links_created_at_idx ON links (created_at DESC)');

    await db(`CREATE TABLE IF NOT EXISTS clicks (

      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, link_id INTEGER NOT NULL REFERENCES links(id) ON DELETE CASCADE,

      code TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), referrer TEXT,

      referrer_domain TEXT, user_agent TEXT, device_type TEXT, browser TEXT, os TEXT,

      country TEXT, country_code TEXT, city TEXT, ip TEXT, variant_id TEXT

    )`);

    await db('CREATE INDEX IF NOT EXISTS clicks_link_created_idx ON clicks (link_id, created_at DESC)');

    await db(`CREATE TABLE IF NOT EXISTS folders (

      id UUID PRIMARY KEY, name TEXT NOT NULL, color TEXT NOT NULL DEFAULT '#64748b',

      icon TEXT NOT NULL DEFAULT 'folder', description TEXT NOT NULL DEFAULT '',

      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()

    )`);

    await db(`ALTER TABLE folders ADD COLUMN IF NOT EXISTS color TEXT NOT NULL DEFAULT '#64748b'`);

    await db(`ALTER TABLE folders ADD COLUMN IF NOT EXISTS icon TEXT NOT NULL DEFAULT 'folder'`);

    await db(`ALTER TABLE folders ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT ''`);

    await db(`CREATE TABLE IF NOT EXISTS campaigns (

      id UUID PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',

      utm_campaign TEXT NOT NULL DEFAULT '', target_clicks INTEGER, start_date TEXT, end_date TEXT,

      color TEXT NOT NULL DEFAULT '#64748b', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()

    )`);

    await db(`ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT ''`);

    await db(`ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS utm_campaign TEXT NOT NULL DEFAULT ''`);

    await db('ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS target_clicks INTEGER');

    await db('ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS start_date TEXT');

    await db('ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS end_date TEXT');

    await db(`ALTER TABLE campaigns ADD COLUMN IF NOT EXISTS color TEXT NOT NULL DEFAULT '#64748b'`);

    await db(`CREATE TABLE IF NOT EXISTS bio_pages (

      id UUID PRIMARY KEY, slug TEXT NOT NULL UNIQUE, title TEXT NOT NULL DEFAULT 'My links',

      bio TEXT NOT NULL DEFAULT '', links JSONB NOT NULL DEFAULT '[]'::jsonb,

      social_links JSONB NOT NULL DEFAULT '[]'::jsonb, total_views INTEGER NOT NULL DEFAULT 0,

      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), avatar_url TEXT, theme TEXT NOT NULL DEFAULT 'slate'

    )`);

    await db('ALTER TABLE bio_pages ADD COLUMN IF NOT EXISTS avatar_url TEXT');

    await db(`ALTER TABLE bio_pages ADD COLUMN IF NOT EXISTS theme TEXT NOT NULL DEFAULT 'slate'`);

    await db('CREATE UNIQUE INDEX IF NOT EXISTS bio_pages_slug_lower_unique ON bio_pages (LOWER(slug))');

  })().catch((e) => { schemaPromise = null; throw e; });

  return schemaPromise;

}

app.use(async (_req, _res, next) => {

  try { await ensureSchema(); next(); } catch (e) { next(e); }

});

