app.get('/api/links', async (req, res, next) => {

  try {

    const conditions = [], values = [];

    const add = (sql, v) => { values.push(v); conditions.push(sql.replace('?', `$${values.length}`)); };

    const q = req.query;

    if (q.search) add("(LOWER(code || ' ' || url || ' ' || title) LIKE '%' || LOWER(?) || '%')", String(q.search));

    if (q.folderId) add('folder_id = ?', String(q.folderId));

    if (q.campaignId) add('campaign_id = ?', String(q.campaignId));

    if (q.tag) add('tags ? ?', String(q.tag).replace(/^#/, '')); // handled below if tag filter present

    if (q.status) add('status = ?', String(q.status));

// JSONB tag operator needs one value; construct it separately to avoid a multi-placeholder helper.

    if (q.tag) { conditions.pop(); values.pop(); values.push(String(q.tag).replace(/^#/, '')); conditions.push(`tags ? $${values.length}`); }

    const sql = `SELECT * FROM links ${conditions.length ? 'WHERE ' + conditions.join(' AND ') : ''} ORDER BY created_at DESC`;

    const r = await db(sql, values);

    res.json({ links: r.rows.map((row) => presentLink(req, fromLinkRow(row))) });

  } catch (e) { next(e); }

});

